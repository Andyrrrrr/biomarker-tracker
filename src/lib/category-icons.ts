export type CategoryIconName = (typeof CATEGORY_ICONS)[number];

export function isCategoryIcon(name: string): name is CategoryIconName {
  return (CATEGORY_ICONS as readonly string[]).includes(name);
}

// "heart-pulse" → "Heart pulse", the icon's accessible name and what the picker's filter matches.
export function categoryIconLabel(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1).replace(/-/g, " ");
}
